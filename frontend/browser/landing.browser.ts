import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const [name, width, height] of [['desktop', 1440, 900], ['tablet', 768, 1024], ['mobile', 390, 844], ['narrow', 360, 844]] as const) {
  test(`${name}: native RTL landing, disclosure, focus and no overflow`, async ({ page }, info) => {
    await page.setViewportSize({ width, height })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await page.evaluate(() => document.fonts.ready)
    await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
    await expect(page.getByLabel('نام کالا')).toHaveValue('')
    await expect(page.getByLabel('عرض جغرافیایی محل انتخابی')).toHaveValue('')
    await expect(page.getByLabel('واحد بودجه')).toHaveValue('')
    await expect(page.locator('.comparison-count')).toHaveText('۰')
    await page.screenshot({ path: info.outputPath(`${name}-landing.png`), fullPage: true })
    await page.keyboard.press('Tab')
    await expect(page.getByRole('link', { name: 'رفتن به محتوای اصلی' })).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    const a11y = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(a11y.violations).toEqual([])
    await page.getByRole('button', { name: 'دیدن پیشنهادها' }).click()
    await expect(page.getByLabel('نام کالا')).toBeFocused()
    await expect(page.getByLabel('نام کالا')).toHaveAttribute('aria-describedby', 'error-query')
    await page.screenshot({ path: info.outputPath(`${name}-errors.png`), fullPage: true })
    const summary = page.locator('.purchase-preferences summary')
    await summary.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByLabel('گارانتی')).toBeVisible()
    await page.getByLabel('کارت', { exact: true }).check()
    await page.getByLabel('گارانتی').selectOption('no')
    await page.getByLabel('مهلت بازگشت (روز، اختیاری)').fill('۱٫۵')
    await summary.click()
    await expect(page.getByLabel('گارانتی')).not.toBeVisible()
    await page.getByLabel('نام کالا').fill('گوشی')
    await page.getByLabel('حداکثر بودجه', { exact: true }).fill('۱۷۰۰۰۰۰۰٫۱۲۳۴۵۶۷۸۹')
    await page.getByLabel('واحد بودجه').selectOption('TOMAN')
    await page.getByLabel('عرض جغرافیایی محل انتخابی').fill('۳۵٫۷')
    await page.getByLabel('طول جغرافیایی محل انتخابی').fill('٥١٫٤')
    await page.getByRole('button', { name: 'دیدن پیشنهادها' }).click()
    await expect(page.getByLabel('مهلت بازگشت (روز، اختیاری)')).toBeFocused()
    await expect(page.locator('.purchase-preferences')).toHaveAttribute('open', '')
    await page.getByLabel('مهلت بازگشت (روز، اختیاری)').fill('۰')
    await expect(page.getByLabel('کارت', { exact: true })).toBeChecked()
    await expect(page.getByLabel('گارانتی')).toHaveValue('no')
    await page.screenshot({ path: info.outputPath(`${name}-preferences.png`), fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    for (const target of await page.locator('.criteria-form input:not([type="checkbox"]), .criteria-form select, .criteria-form summary, .criteria-form button, .payment-options label').all()) {
      if (await target.isVisible()) {
        const bounds = await target.boundingBox()
        expect(bounds?.height).toBeGreaterThanOrEqual(44)
        expect(bounds?.width).toBeGreaterThanOrEqual(44)
      }
    }
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    if (width <= 576) {
      const menu = page.getByRole('button', { name: 'فهرست ناوبری' })
      await expect(page.getByRole('navigation')).not.toBeVisible()
      await menu.click()
      await expect(menu).toHaveAttribute('aria-expanded', 'true')
      await page.getByRole('link', { name: /^مقایسه / }).focus()
      await page.keyboard.press('Escape')
      await expect(menu).toBeFocused()
      await menu.click()
    }
    await page.getByRole('link', { name: /^مقایسه / }).click()
    await expect(page.getByRole('region', { name: 'مقایسهٔ خرید' })).toBeFocused()
    if (width <= 576) await page.getByRole('button', { name: 'فهرست ناوبری' }).click()
    await page.getByRole('link', { name: 'راهنمای خرید', exact: true }).click()
    await expect(page.getByRole('region', { name: 'راهنمای خرید' })).toBeFocused()
    await expect(page.getByLabel('حداکثر بودجه', { exact: true })).toHaveValue('۱۷۰۰۰۰۰۰٫۱۲۳۴۵۶۷۸۹')
    await expect(page.locator('#recommendation-root')).toBeEmpty()
    expect(errors).toEqual([])
  })
}

test('HTTP failure keeps exact submitted criteria; editing advances revision before retry', async ({ page }) => {
  const requests: { request_id: string; revision: number; criteria: { max_budget: string; price_unit: string } }[] = []
  await page.route('**/api/v1/journey/recommendations', async route => {
    requests.push(route.request().postDataJSON())
    await route.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ error: {
      code: 'invalid_request', message: 'not displayed', details: [{ loc: ['body', 'criteria', 'max_budget'] }],
    } }) })
  })
  await page.goto('/')
  await page.getByLabel('نام کالا').fill('گوشی')
  await page.getByLabel('حداکثر بودجه', { exact: true }).fill('۱۲۳٫۴۵۶۷۸۹')
  await page.getByLabel('واحد بودجه').selectOption('IRR')
  await page.getByLabel('عرض جغرافیایی محل انتخابی').fill('۳۵٫۷')
  await page.getByLabel('طول جغرافیایی محل انتخابی').fill('۵۱٫۴')
  await page.getByRole('button', { name: 'دیدن پیشنهادها' }).click()
  await expect(page.getByLabel('حداکثر بودجه', { exact: true })).toBeFocused()
  await expect(page.getByRole('alert')).toHaveText('اطلاعات فرم را بررسی کنید.')
  await expect(page.getByLabel('حداکثر بودجه', { exact: true })).toHaveValue('۱۲۳٫۴۵۶۷۸۹')
  expect(requests[0].criteria).toMatchObject({ max_budget: '123.456789', price_unit: 'IRR' })
  await page.getByRole('button', { name: 'تلاش دوباره' }).click()
  await expect.poll(() => requests.length).toBe(2)
  expect(requests[1]).toEqual(requests[0])
  await page.getByLabel('نام کالا').fill('گوشی جدید')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'دیدن پیشنهادها' }).click()
  await expect.poll(() => requests.length).toBe(3)
  expect(requests[2].request_id).toBe(requests[0].request_id)
  expect(requests[2].revision).toBeGreaterThan(requests[0].revision)
})
