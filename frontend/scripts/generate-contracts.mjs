import { spawnSync } from 'node:child_process'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { compile } from 'json-schema-to-typescript'

const frontend = fileURLToPath(new URL('../', import.meta.url))
const root = path.dirname(frontend.replace(/[\\/]$/, ''))
const check = process.argv.includes('--check')
const source = JSON.parse(await readFile(new URL('./contract-source.json', import.meta.url), 'utf8'))
const run = spawnSync('uv', [
  'run', '--project', root, '--frozen', '--no-dev', 'python',
  fileURLToPath(new URL('./export_contracts.py', import.meta.url)),
], { cwd: frontend, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
if (run.status !== 0) {
  process.stderr.write(run.stderr || run.error?.message || 'Schema export failed.\n')
  process.exit(1)
}
const data = JSON.parse(run.stdout)
const bannerComment = `/* Generated by npm run contracts:generate. Do not edit.
 * Recommendation/Catalog: current canonical Python models.
 * Pending Journey: ${source.journeyRef}
 */`
const options = { bannerComment, unknownAny: true, style: { singleQuote: true } }
const outputs = new Map()
for (const [kind, schema] of [['requests', data.requestSchema], ['responses', data.responseSchema]]) {
  outputs.set(`src/contracts/generated/${kind}.ts`, await compile(schema, 'BackendContracts', options))
  outputs.set(`src/contracts/generated/${kind}.schema.json`, `${JSON.stringify(schema, null, 2)}\n`)
}
const types = {
  alternativesFixture: 'AlternativesResponse', recommendationFixture: 'RecommendationResponse',
  errorFixture: 'ErrorResponse', journeyFixture: 'JourneyRecommendations', requestFixture: 'ShoppingRequest',
  acceptanceFixture: 'AlternativeAcceptance',
}
// Generate typed object literals, rather than casting unvalidated JSON in tests.
let fixtures = `${bannerComment}\nimport type { AlternativesResponse, RecommendationResponse, ErrorResponse, JourneyRecommendations } from '../../contracts/generated/responses'\nimport type { ShoppingRequest, AlternativeAcceptance } from '../../contracts/generated/requests'\n`
for (const [name, value] of Object.entries(data.fixtures)) {
  fixtures += `\nexport const ${name}: ${types[name]} = ${JSON.stringify(value, null, 2)}\n`
}
outputs.set('src/test/fixtures/contracts.ts', fixtures)
let drift = false
for (const [name, contents] of outputs) {
  const target = path.join(frontend, name)
  const existing = await readFile(target, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error
    return null
  })
  if (existing === contents) continue
  if (check) {
    console.error(`Contract drift: ${name}`)
    drift = true
  } else {
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, contents, 'utf8')
  }
}
if (drift) process.exit(1)
console.log(check ? 'Canonical schemas, bindings and validated fixtures match.' : 'Contracts and fixtures generated.')
